// Actual Vue/WebGL and Java endpoints, with isolated account cookies and synthetic labelled images.
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.SKYTWIN_PLAYWRIGHT_MODULE || 'playwright')
const prefix = process.env.SKYTWIN_UI_PREFIX, source = process.env.SKYTWIN_UI_SOURCE, aircraft = process.env.SKYTWIN_UI_AIRCRAFT
const stations = JSON.parse(process.env.SKYTWIN_UI_STATIONS || '[]')
assert(/^ev_[a-f0-9]+$/.test(prefix) && source && aircraft && stations.length === 2)
const base = 'http://127.0.0.1:5173', title = prefix + '_ui'
const report = { passed: false, checks: [], transport: 'Real Java API, actual uploads, no mocked business responses.' }
const check = name => { report.checks.push(name); console.log('PASS UI: ' + name) }
let browser
try {
  const options = { headless: true, args: ['--enable-unsafe-swiftshader'] }
  try { browser = await chromium.launch({ ...options, channel: 'chrome' }) }
  catch { browser = await chromium.launch(options) }
  const context = await browser.newContext({ viewport: { width: 1720, height: 1080 }, locale: 'zh-CN' })
  await context.addCookies([{ name: 'Admin-Token', value: process.env.SKYTWIN_UI_ADMIN_TOKEN, url: base }])
  const page = await context.newPage(), errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(base + '/environment')
  await page.getByRole('heading', { name: '环境发现 → 应急处置闭环', exact: true }).waitFor()
  await page.getByRole('combobox', { name: '关联巡检任务', exact: true }).selectOption(source)
  await page.getByRole('textbox', { name: '发现标题', exact: true }).fill(title)
  await page.getByRole('spinbutton', { name: '发现经度', exact: true }).fill('120.19')
  await page.getByRole('spinbutton', { name: '发现纬度', exact: true }).fill('30.216')
  await page.getByRole('textbox', { name: '人工标注说明', exact: true }).fill('仿真图片人工标注，非AI识别')
  await page.getByLabel('发现图片', { exact: true }).setInputFiles({ name: 'simulation-before.png', mimeType: 'image/png', buffer: Buffer.from(process.env.SKYTWIN_UI_BEFORE, 'hex') })
  const createdResponse = page.waitForResponse(r => r.url().endsWith('/sky/environment/discoveries') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '提交发现，等待人工复核', exact: true }).click()
  const created = await (await createdResponse).json()
  assert.equal(created.code, 200)
  const discovery = created.data.id, url = base + '/environment?discoveryId=' + discovery
  await page.getByText('发现已保存，等待人工复核；尚未生成事件', { exact: true }).waitFor()
  await page.getByRole('heading', { name: title + ' · 待人工复核', exact: true }).waitFor()
  await page.waitForFunction(() => [...document.images].some(img => img.alt === '人工标注的发现证据' && img.complete && img.naturalWidth === 1600))
  assert.equal(await page.locator('.image-wrap .box').count(), 1)
  const boxGeometry = await page.locator('.image-wrap').evaluate(el => { const image = el.querySelector('img').getBoundingClientRect(), box = el.querySelector('.box').getBoundingClientRect(), wrap = el.getBoundingClientRect(); return { imageWidth: image.width, wrapWidth: wrap.width, boxWidth: box.width, boxLeft: box.left - image.left } })
  assert(Math.abs(boxGeometry.imageWidth - boxGeometry.wrapWidth) < 1)
  assert(Math.abs(boxGeometry.boxWidth / boxGeometry.imageWidth - .5) < .01)
  assert(Math.abs(boxGeometry.boxLeft / boxGeometry.imageWidth - .2) < .01)
  check('multipart upload persists discovery and renders authorized original image with human annotation')
  await page.getByRole('button', { name: '定位发现点', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('.scene-message'), null, { timeout: 45000 })
  assert.match(await page.locator('.map-note').innerText(), /用户标注/)
  assert.equal(await page.locator('.city-canvas canvas').count(), 1)
  check('actual digital twin focuses user-declared location without claiming automatic geolocation')
  await page.getByRole('combobox', { name: '复核事件等级', exact: true }).selectOption('high')
  await page.getByRole('textbox', { name: '环境复核原因', exact: true }).fill(prefix + '_ui_review')
  await page.getByRole('button', { name: '确认异常并生成事件', exact: true }).click()
  await page.getByText('复核已确认并生成环境事件', { exact: true }).waitFor()
  check('human review creates a real geographic event')
  await page.getByRole('combobox', { name: '应急侦察出发站', exact: true }).selectOption(stations[0])
  await page.getByRole('combobox', { name: '应急侦察回收站', exact: true }).selectOption(stations[1])
  await page.getByRole('textbox', { name: '应急任务原因', exact: true }).fill(prefix + '_ui_response')
  await page.getByRole('button', { name: '创建应急侦察任务', exact: true }).click()
  await page.getByText('应急侦察任务及事件上空航线已创建，请分配并执行或进入集群调度', { exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: '提交证据并结案归档', exact: true }).isDisabled(), true)
  check('response mission uses existing task engine and premature closure stays disabled')
  await page.getByRole('combobox', { name: '应急分配飞行器', exact: true }).selectOption(aircraft)
  await page.getByRole('button', { name: '分配侦察飞行器', exact: true }).click()
  await page.getByRole('button', { name: '执行应急侦察', exact: true }).waitFor()
  await page.getByRole('button', { name: '执行应急侦察', exact: true }).click()
  await page.getByRole('heading', { name: title + ' · 应急处置中', exact: true }).waitFor()
  await page.waitForFunction(() => document.querySelector('textarea[aria-label="环境处置说明"]')?.disabled === false, null, { timeout: 65000 })
  check('Java executes reconnaissance along incident waypoint before enabling closure')
  await page.getByRole('textbox', { name: '环境处置说明', exact: true }).fill(prefix + ' 仿真处置后人工复核，非真实清理')
  await page.getByLabel('处置后图片', { exact: true }).setInputFiles({ name: 'simulation-after.png', mimeType: 'image/png', buffer: Buffer.from(process.env.SKYTWIN_UI_AFTER, 'hex') })
  await page.getByRole('button', { name: '提交证据并结案归档', exact: true }).click()
  await page.getByText('事件、处置后证据和归档报告已一并保存', { exact: true }).waitFor()
  await page.getByRole('heading', { name: '不可变归档报告', exact: true }).waitFor()
  await page.waitForFunction(() => [...document.images].some(img => img.alt === '人工提交的处置后证据' && img.complete && img.naturalWidth === 1600))
  check('post-treatment evidence atomically closes incident and creates immutable report')
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载环境处置报告', exact: true }).click()
  const download = await downloaded, file = await download.path()
  assert.match(await readFile(file, 'utf8'), /非AI识别、非真实救援/)
  await page.getByRole('button', { name: '查看证据快照', exact: true }).click()
  assert.match(await page.locator('.card pre').last().innerText(), /latestResponseTracks/)
  check('downloaded report and frozen snapshot preserve evidence provenance and actual simulation tracks')
  await page.goto(url)
  await page.getByRole('heading', { name: title + ' · 已归档', exact: true }).waitFor()
  await page.getByRole('heading', { name: '不可变归档报告', exact: true }).waitFor()
  await mkdir(resolve('docs/verification'), { recursive: true })
  await page.getByRole('button', { name: '定位发现点', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('.scene-message'), null, { timeout: 45000 })
  await page.locator('.map').screenshot({ path: resolve('docs/verification/environment-incident-map.png') })
  await page.getByRole('heading', { name: '不可变归档报告', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: resolve('docs/verification/environment-closed-report.png'), fullPage: true })
  check('deep-link reload restores archived images event and report')
  await page.goto(base + '/patrol-report')
  const reportRow = page.locator('.list article').filter({ hasText: title })
  await reportRow.getByRole('button', { name: '查看环境归档报告', exact: true }).click()
  await page.getByRole('heading', { name: '不可变归档报告', exact: true }).waitFor()
  check('patrol reports expose environmental archive with trace-back link')
  const viewerContext = await browser.newContext({ viewport: { width: 1720, height: 1080 }, locale: 'zh-CN' })
  await viewerContext.addCookies([{ name: 'Admin-Token', value: process.env.SKYTWIN_UI_VIEWER_TOKEN, url: base }])
  const viewer = await viewerContext.newPage()
  await viewer.goto(url)
  await viewer.getByRole('heading', { name: title + ' · 已归档', exact: true }).waitFor()
  assert.equal(await viewer.getByRole('textbox', { name: '发现标题', exact: true }).isDisabled(), true)
  await viewer.getByRole('heading', { name: '不可变归档报告', exact: true }).waitFor()
  check('viewer reads image and archive but cannot submit discoveries')
  await viewerContext.close()
  await page.goto(base + '/emergency-process')
  await page.getByRole('heading', { name: '环境事件应急处置', exact: true }).waitFor()
  assert.deepEqual(errors, [])
  check('emergency integration and repeated scene disposal have no uncaught browser errors')
  report.passed = true
} catch (e) { report.error = String(e); throw e }
finally { await browser?.close(); await writeFile(resolve('ruoyi/logs/environment-ui-verification.json'), JSON.stringify(report, null, 2)) }
